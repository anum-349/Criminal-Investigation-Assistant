/**
 * Build an AI-generated lead. Used by the lead-analysis pipeline (or its
 * mock equivalent in StepAIAnalysis).
 *
 * Keeps the shape your existing CaseLeads / LeadSuggestionPanel render.
 */
export function createAILead({
  caseId,
  type,
  description,
  confidence       = 0,
  severity         = "Medium",
  suggestedSuspect = null,
  similarCase      = null,
  nextStep         = "",
  status           = "New",
} = {}) {
  return {
    id:               generateId('LEAD', caseId, 10),
    caseId,
    eventSource:      EVENT_SOURCE.AI,
    type,
    description,
    confidence,
    severity,
    status,
    suggestedSuspect,
    similarCase,
    nextStep,
    source:           "AI Analysis",
    generatedAt:      new Date().toISOString(),
    // AI leads can have status changed but should not be hard-deleted —
    // dismissal is preferred so the audit trail is preserved.
    editable:         false,
    dismissable:      true,
  };
}

/**
 * Build a manual lead from the AddLeadModal form.
 * Manual leads support full edit + delete because the investigator owns them.
 */
export function createManualLead(form, caseId) {
  return {
    id:               generateId('LEAD', caseId, 10),
    caseId:           form.caseId || caseId,
    eventSource:      EVENT_SOURCE.MANUAL,
    type:             form.type,
    description:      form.description,
    severity:         form.severity || "Medium",
    status:           form.status || "New",
    // confidence is intentionally null — manual leads don't have an AI score
    confidence:       null,
    suggestedSuspect: form.suggestedSuspect || null,
    similarCase:      null,
    nextStep:         form.nextStep || "",
    source:           form.source || "Officer Entry",
    officerName:      form.officerName || "",
    generatedAt:      new Date().toISOString(),
    editable:         true,
    dismissable:      true,
  };
}

