// 7. ID GENERATORS
// ═════════════════════════════════════════════════════════════════════════════
// Same convention as your existing generateSuspectId / generateVictimId /
// generateWitnessId. Pure functions — call them from factories below.

const _ts = () => Date.now().toString(36).toUpperCase();
const _rand = () => Math.random().toString(36).substring(2, 5).toUpperCase();

const pad = (num) => String(num).padStart(2, '0');

export const generateId = (prefix, caseId, count) => {
  return `${prefix}-${caseId}-${pad(count + 1)}`;
};

// ═════════════════════════════════════════════════════════════════════════════
// 8. FACTORIES — Timeline Events
// ═════════════════════════════════════════════════════════════════════════════
// USE THESE — never construct events inline. Two factories: one for system
// events emitted by action handlers, one for manual entries from the modal.

const _todayDate = () => new Date().toISOString().split("T")[0];
const _todayTime = () => new Date().toTimeString().slice(0, 5);

/**
 * Build a system-emitted timeline event. Call from action handlers like
 *   AddSuspectDialog.onSubmit, AddEvidenceDialog.onSubmit, etc.
 *
 * @param {object} params
 * @param {string} params.caseId          — case the event belongs to
 * @param {string} params.eventType       — must be a value from SYSTEM_EVENT
 * @param {string} params.title           — short headline shown in the timeline
 * @param {string} [params.description]   — optional longer description
 * @param {string} [params.officerName]   — defaults to "System"
 * @param {object} [params.payload]       — small structured blob (e.g. { suspectId, suspectName }) for downstream linking
 * @param {string} [params.severity]      — one of SEVERITIES, defaults to "Normal"
 */
export function createSystemEvent({
  caseId,
  eventType,
  title,
  description = "",
  officerName = "System",
  payload     = null,
  severity    = "Normal",
} = {}) {
  return {
    id:           generateId('EVT', caseId, 10),
    caseId,
    eventSource:  EVENT_SOURCE.SYSTEM,
    eventType,
    title,
    description,
    officerName,
    severity,
    payload,
    date:         _todayDate(),
    time:         _todayTime(),
    createdAt:    new Date().toISOString(),
    // System events are immutable — UI should not let users delete them.
    editable:     false,
  };
}

/**
 * Build a manual timeline event from the AddTimelineModal's form.
 * Pass the modal's form state directly.
 *
 * @param {object} form  — the AddTimelineModal form object
 * @param {string} caseId
 */
export function createManualEvent(form, caseId) {
  return {
    id:               generateId('EVT', caseId, 10),
    caseId:           form.caseId || caseId,
    eventSource:      EVENT_SOURCE.MANUAL,
    eventType:        form.eventType,
    title:            form.title,
    description:      form.description,
    officerName:      form.officerName,
    severity:         form.severity || "Normal",
    location:         form.location || "",
    outcome:          form.outcome || "",
    attachmentNote:   form.attachmentNote || "",
    followUpRequired: !!form.followUpRequired,
    followUpDate:     form.followUpDate || "",
    date:             form.date || _todayDate(),
    time:             form.time || _todayTime(),
    createdAt:        new Date().toISOString(),
    editable:         true,
  };
}

