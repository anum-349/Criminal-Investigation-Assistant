/**
 * Build an investigation note. Notes are always manual.
 *
 * @param {object} form   — the Notes-tab modal form object
 *   { caseId, officerName, date, title, detail, category? }
 */
export function createNote(form, caseId) {
  return {
    id:          generateId('NOTE', caseId, 10),
    caseId:      form.caseId || caseId,
    officerName: form.officerName,
    date:        form.date || _todayDate(),
    title:       form.title,
    detail:      form.detail,
    category:    form.category || "General Observation",
    createdAt:   new Date().toLocaleTimeString("en-PK", {
                   hour: "2-digit", minute: "2-digit",
                 }),
    editable:    true,
  };
}

