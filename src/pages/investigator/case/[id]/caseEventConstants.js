/**
 * caseEventConstants.js
 * ─────────────────────────────────────────────────────────────────────────────
 * Single source of truth for the three types of records that get attached to a
 * case AFTER it has been registered:
 *
 *   • Timeline Events  — system-logged or manually entered moments in time
 *   • Investigation Leads — AI-suggested or manually entered investigative leads
 *   • Investigation Notes — investigator's working notes (separate "Notes" tab)
 *
 * Why this file matters:
 * Because the project does not (yet) have a central state store, the ONLY thing
 * keeping these records consistent across tabs and dialogs is the factory
 * functions defined here. Always create new records via these factories — never
 * inline. That guarantees the shape stays in sync as the codebase grows.
 *
 * Place at: src/pages/investigator/case/caseEventConstants.js
 *
 * (Co-located with the case tabs that consume it. If you'd rather keep all
 * constants together, src/pages/form/caseFormConstants/page.jsx
 * is also fine — but importing from there would couple this file to the
 * registration-form scope, which is conceptually different from "things that
 * happen to a case after it's registered".)
 * ─────────────────────────────────────────────────────────────────────────────
 */

